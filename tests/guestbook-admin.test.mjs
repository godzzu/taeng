import assert from "node:assert/strict";
import { createAdminApi, guestbookCsv } from "../js/services/guestbook-admin-api.js";
const settings = { guestbookProvider: "supabase", supabaseUrl: "https://example.supabase.co", supabasePublishableKey: "sb_publishable_test" };
const requests = [];
let result = {}, status = 200;
const api = createAdminApi(settings, async (url, options) => {
  requests.push({ url, ...options, body: JSON.parse(options.body) });
  return { ok: status === 200, status, json: async () => result };
});
assert.equal(api.configured, true);
assert.equal(createAdminApi({ ...settings, supabaseUrl: "http://example.com" }).configured, false);
assert.equal(createAdminApi({ ...settings, supabasePublishableKey: "sb_secret_test" }).configured, false);
result = { error: "invalid_credentials" };
await assert.rejects(api.login("board-a", "wrong"), { code: "invalid_credentials" });
result = { token: "a".repeat(64) };
await api.login(" board-a ", "secret-password");
assert.equal(requests.at(-1).body.p_wedding_id, "board-a");
const row = { id: "9007199254740993", name: "=1+1", message: 'Hello, "world"\nNext line', approved: false, created_at: "2026-11-08T00:00:00Z" };
result = { entries: [row], has_more: false, max_id: row.id };
const page = await api.list();
assert.equal(page.entries[0].id, row.id);
assert.equal(requests.at(-1).body.p_password, undefined);
assert.equal(requests.at(-1).body.p_token, "a".repeat(64));
result = { ok: true };
await api.approve(row.id, true);
assert.equal(requests.at(-1).body.p_entry_id, row.id);
assert.equal(requests.at(-1).body.p_approved, true);
await api.remove(row.id);
assert.equal(requests.at(-1).body.p_action, "delete");
const csv = guestbookCsv([row, { ...row, name: " \t@SUM(1)", message: "-1+2" }]);
assert(csv.startsWith("\uFEFF")); assert(csv.includes('"\'=1+1"'));
assert(csv.includes('Hello, ""world""\nNext line')); assert(csv.includes("09:00:00"));
assert(csv.includes("' \t@SUM(1)")); assert(csv.includes("'-1+2"));
status = 404;
await assert.rejects(api.list(), { code: "not_installed" });
status = 200; result = { error: "unauthorized" };
await assert.rejects(api.list(), { code: "unauthorized" });
result = { ok: true };
await api.logout();
result = { entries: [], has_more: false, max_id: "0" };
await api.list(); assert.equal(requests.at(-1).body.p_token, null);
let pages = 0;
const exporter = createAdminApi(settings, async (url, options) => {
  const body = JSON.parse(options.body);
  if (body.p_action === "login") return { ok: true, json: async () => ({ token: "b".repeat(64) }) };
  pages++;
  if (pages === 2) { assert.equal(body.p_before, row.id); assert.equal(body.p_max_id, row.id); }
  return { ok: true, json: async () => ({ entries: [{ ...row, id: pages === 1 ? row.id : "2" }], has_more: pages === 1, max_id: row.id }) };
});
await exporter.login("a", "b");
assert.equal((await exporter.exportAll()).length, 2);
console.log("PASS: admin login/session payloads, approval/delete, pagination export, large IDs, CSV escaping/formula protection, errors and logout");
